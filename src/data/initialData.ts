export function createInitialPeriod(employees: Employee[], settings: CompanySettings): PayrollPeriod {
  const periodId = '2026-10';
  const items: Record<string, any> = {};
  const results: Record<string, any> = {};

  employees.forEach((emp) => {
    // Definir inputs padrões
    const input = {
      employeeId: emp.id,
      daysWorked: 22,
      daysAbsentUnjustified: emp.id === 'emp-005' ? 1 : 0, // Carlos teve 1 falta
      overtimeHoursDay: emp.id === 'emp-007' ? 12 : emp.id === 'emp-002' ? 6 : 0, // Motorista com 12h extras
      overtimeHoursNight: emp.id === 'emp-007' ? 4 : 0,
      bonus: emp.id === 'emp-003' ? 25000 : 0, // Prémio de fecho contabilístico
      salaryAdvance: emp.id === 'emp-004' ? 30000 : 0, // Adiantamento
      unionFeePercent: 1, // 1% sindicato
      otherDeductions: 0
    };

    items[emp.id] = input;
    results[emp.id] = calculateEmployeePayroll(emp, input, settings, periodId);
  });

  return {
    id: periodId,
    month: 10,
    year: 2026,
    label: 'Outubro 2026',
    type: 'regular',
    status: 'approved',
    createdAt: '2026-10-01T08:00:00Z',
    processedAt: '2026-10-25T14:30:00Z',
    approvedAt: '2026-10-26T10:00:00Z',
    processedBy: 'Dra. Maria Esperança Manuel',
    items,
    results
  };
}
